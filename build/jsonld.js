// Generates the Person JSON-LD block on index.html from SITE_DATA, so the
// structured data can never drift from the rest of the site.
const fs = require('fs');
process.chdir('C:\\Users\\kylak\\Portfolio Website\\personalwebsite');

const D = new Function(fs.readFileSync('data.js', 'utf8') + '\nreturn SITE_DATA;')();
const SITE = D.site_url || 'https://kylafallis.com';

const sameAs = [D.linkedin, D.github, D.fairgame_url, D.scholar, D.orcid].filter(Boolean);

const person = {
  '@context': 'https://schema.org',
  '@type': 'Person',
  name: D.name,
  url: SITE + '/',
  image: SITE + '/images/share.jpg',
  email: D.email ? 'mailto:' + D.email : undefined,
  jobTitle: ['Chemical Engineering Student', 'Researcher', 'Co-Founder & CTO', 'Founder & Executive Director'],
  description: D.tagline,
  alumniOf: { '@type': 'EducationalOrganization', name: 'Bath High School' },
  affiliation: [
    { '@type': 'CollegeOrUniversity', name: 'The Ohio State University', url: 'https://www.osu.edu' },
    { '@type': 'NonprofitOrganization', name: 'FairGame Initiative', url: D.fairgame_url }
  ],
  worksFor: { '@type': 'NonprofitOrganization', name: 'FairGame Initiative', url: D.fairgame_url },
  knowsAbout: [
    'Chemical Engineering', 'Environmental engineering', 'Deep-sea electrochemistry', 'Dark oxygen production',
    'Renewable energy', 'Physics-informed machine learning', 'Tidal energy',
    'Microbial fuel cells', 'Science policy', 'STEM education equity'
  ],
  sameAs
};

// Each publication as a ScholarlyArticle, linked to the author.
const pubs = D.research.filter(r => !r.secondary).map(r => {
  const o = {
    '@context': 'https://schema.org',
    '@type': 'ScholarlyArticle',
    headline: r.title,
    author: { '@type': 'Person', name: D.name, url: SITE + '/' },
    publisher: { '@type': 'Organization', name: r.journal },
    abstract: r.summary,
    url: SITE + '/research.html#' + r.id
  };
  if (r.doi) { o.identifier = 'https://doi.org/' + r.doi; o.sameAs = 'https://doi.org/' + r.doi; }
  return o;
});

const graph = [person, ...pubs];
const json = JSON.stringify(graph.length === 1 ? graph[0] : graph, null, 2)
  .split('\n').map(l => '    ' + l).join('\n');

const block = '  <!-- Structured data (generated by build/jsonld.js, do not hand-edit) -->\n' +
  '  <script type="application/ld+json">\n' + json + '\n  </script>\n';

let s = fs.readFileSync('index.html', 'utf8');
// CRLF-safe and global: these files are checked out with Windows line endings,
// and a non-global regex left a stale block behind, producing duplicates.
s = s.replace(/[ \t]*<!-- Structured data[\s\S]*?<\/script>\r?\n/g, '');
s = s.replace('  <link rel="stylesheet" href="style.css">', block + '\n  <link rel="stylesheet" href="style.css">');
fs.writeFileSync('index.html', s);

console.log('JSON-LD written:', graph.length, 'node(s):', 1, 'Person +', pubs.length, 'ScholarlyArticle');
console.log('sameAs:', sameAs.length, 'profile link(s)');
